export function seoUsefulnessLaneFor(input = {}){
  const category = typeof input === "string" ? input : input.category || ""
  const title = typeof input === "string" ? "" : input.title || input.slug || ""
  const keywords = typeof input === "string" ? [] : input.keywords || input.seo_keywords || []
  const haystack = `${category} ${title} ${keywords.join(" ")}`.toLowerCase()
  return seoUsefulnessLaneMap.find((lane) => lane.categoryMatchers.some((matcher) => haystack.includes(matcher))) || seoUsefulnessLaneMap[0]
}

