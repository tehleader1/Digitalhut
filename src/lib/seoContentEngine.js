function uniqueClean(values = []){
  return Array.from(new Set(values.map((value) => String(value || "").trim()).filter(Boolean)))
}

function normalizedText(value = ""){
  return String(value || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim()
}

export function seoMasterListLanesFor(input = {}, limit = 3){
  const category = typeof input === "string" ? input : input.category || ""
  const title = typeof input === "string" ? "" : input.title || input.slug || ""
  const keywords = typeof input === "string" ? [] : input.keywords || input.seo_keywords || []
  const haystack = normalizedText(`${category} ${title} ${keywords.join(" ")}`)
  const common = new Set(["digitalhut", "visual", "video", "view", "source", "proof", "route", "watch", "guide", "with", "near", "2026", "experience", "observatory", "moment", "context", "system"])
  const hayTokens = new Set(haystack.split(" ").filter((term) => term.length > 3 && !common.has(term)))
  const aliasIds = Object.entries(seoMasterListAliasMap).filter(([key]) => haystack.includes(key)).flatMap(([, ids]) => ids)
  const aliasScore = new Map(aliasIds.map((id, index) => [id, 30 - index]))
  const scored = seoMasterListLanes.map((lane) => {
    const lanePhrases = [lane.id, lane.lane, lane.category, ...lane.sampleKeywords, ...lane.nextCandidateQueue.map((item) => item.keyword)]
    const exactScore = lanePhrases.some((phrase) => haystack.includes(normalizedText(phrase))) ? 24 : 0
    const tokenScore = lanePhrases.reduce((score, phrase) => {
      const tokens = normalizedText(phrase).split(" ").filter((term) => term.length > 3 && !common.has(term))
      return score + tokens.filter((term) => hayTokens.has(term)).length
    }, 0)
    return {lane, score: (aliasScore.get(lane.id) || 0) + exactScore + tokenScore}
  })
  const ranked = scored.filter((item) => item.score > 0).sort((a, b) => b.score - a.score).map((item) => item.lane)
  return uniqueClean([...ranked, seoMasterListLanes[0]].map((lane) => lane.id))
    .map((id) => seoMasterListLanes.find((lane) => lane.id === id))
    .filter(Boolean)
    .slice(0, limit)
}

export function seoMasterListKeywordsFor(input = {}, limit = 18){
  const lanes = seoMasterListLanesFor(input, 3)
  const postKeywords = typeof input === "string" ? [] : input.keywords || input.seo_keywords || []
  const keywords = lanes.flatMap((lane) => [
    ...lane.sampleKeywords,
    ...lane.nextCandidateQueue.map((item) => item.keyword),
    `${lane.lane} DigitalHut proof route`,
    `${lane.role} DigitalHut observatory`
  ])
  return uniqueClean([...postKeywords, ...keywords]).slice(0, limit)
}

